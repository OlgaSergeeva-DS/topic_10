# ========== 1. ЗАДАЧА О РЮКЗАКЕ ==========
def knapsack(weights, values, capacity):
    """
    Задача о рюкзаке (0-1).
    Возвращает максимальную стоимость предметов, которые влезут в рюкзак.
    """
    n = len(weights)
    # Создаем таблицу DP размером (n+1) x (capacity+1), заполненную нулями.
    # dp[i][w] будет хранить максимальную стоимость, используя первые i предметов
    # с ограничением веса w.
    dp = [[0 for _ in range(capacity + 1)] for _ in range(n + 1)]

    # Заполняем таблицу
    for i in range(1, n + 1):
        for w in range(1, capacity + 1):
            # Если текущий предмет весит больше, чем текущая вместимость w
            if weights[i - 1] > w:
                # Мы не можем его взять, берем результат без него
                dp[i][w] = dp[i - 1][w]
            else:
                # Выбираем максимум: либо не берем предмет,
                # либо берем его (стоимость + лучший результат для оставшегося веса)
                dp[i][w] = max(
                    dp[i - 1][w],
                    values[i - 1] + dp[i - 1][w - weights[i - 1]]
                )

    # Максимальная стоимость лежит в правом нижнем углу таблицы
    return dp[n][capacity]


# ========== 2. НАИБОЛЬШАЯ ОБЩАЯ ПОДПОСЛЕДОВАТЕЛЬНОСТЬ (LCS) ==========
def longest_common_subsequence(s1, s2):
    """
    Находит длину наибольшей общей подпоследовательности двух строк.
    """
    m, n = len(s1), len(s2)

    # Таблица dp: (m+1) x (n+1)
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    for i in range(1, m + 1):
        for j in range(1, n + 1):
            # Если символы совпадают, увеличиваем длину на 1
            if s1[i - 1] == s2[j - 1]:
                dp[i][j] = dp[i - 1][j - 1] + 1
            else:
                # Иначе берем максимум из "пропустить символ из s1" или "из s2"
                dp[i][j] = max(dp[i - 1][j], dp[i][j - 1])

    return dp[m][n]


# ========== 3. РАЗБИТЬ ЧИСЛО НА СУММУ (ЧИСЛА ФИБОНАЧЧИ/ЛЕСТНИЦА) ==========
def count_ways_to_sum(n):
    """
    Находит количество способов разбить число n на сумму чисел.
    По сути, это задача "посчитать количество путей до n-й ступеньки",
    где шагать можно на 1, 2, 3 и т.д. (или классическая задача о размене монет,
    где номиналы равны 1, 2, 3... n).
    """
    # dp[i] будет хранить количество способов получить сумму i
    dp = [0] * (n + 1)
    dp[0] = 1  # База: сумму 0 можно получить 1 способом (ничего не брать)

    # Проходимся по всем возможным "числам" (от 1 до n)
    for num in range(1, n + 1):
        # Обновляем способы для всех сумм от num до n
        for i in range(num, n + 1):
            dp[i] += dp[i - num]

    return dp[n]


# ========== 4. АЛГОРИТМ ФЛОЙДА-УОРШЕЛЛА ==========
def floyd_warshall(graph):
    """
    Находит кратчайшие пути между всеми парами вершин.
    graph — матрица смежности, где graph[i][j] — вес ребра.
    Если ребра нет, должно быть float('inf').
    """
    n = len(graph)
    # Делаем копию матрицы, чтобы не портить исходную
    dist = [row[:] for row in graph]

    # Перебираем все возможные промежуточные вершины k
    for k in range(n):
        # Для каждой начальной вершины i
        for i in range(n):
            # Для каждой конечной вершины j
            for j in range(n):
                # Если путь через вершину k короче, чем прямой путь из i в j
                if dist[i][k] + dist[k][j] < dist[i][j]:
                    dist[i][j] = dist[i][k] + dist[k][j]

    return dist


